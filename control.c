#include <stdio.h>
#include <stdlib.h>

#define PI 3.14

int add(int a, int b);
void recursive_function(int n);

int main() {

  /* 00. if statement */
  //##############################################################################
    int a = 10;
    if (a > 5) {
        printf("a is greater than 5\n");
    } else {
        printf("a is not greater than 5\n");
    }
  //##############################################################################

  /* 01. switch-case */
  //##############################################################################
    int day = 3;
    switch (day) {
        case 1: printf("Monday\n"); break;
        case 2: printf("Tuesday\n"); break;
        case 3: printf("Wednesday\n"); break;
        default: printf("Other day\n"); break;
    }
  //##############################################################################

  /* 02. for loop */
  //##############################################################################
    for (int i = 0; i < 3; i++) {
        printf("for loop iteration %d\n", i);
    }
  //##############################################################################

  /* 03. while loop */
  //##############################################################################
    int count = 0;
    while (count < 3) {
        printf("while loop iteration %d\n", count);
        count++;
    }
  //##############################################################################

  /* 04. do-while loop */
  //##############################################################################
    int num = 0;
    do {
        printf("do-while loop iteration %d\n", num);
        num++;
    } while (num < 3);
  //##############################################################################

  /* 05. function */
  //##############################################################################
    int sum = add(5, 7);
    printf("Sum: %d\n", sum);
  //##############################################################################

  /* 06. recursion */
  //##############################################################################
    recursive_function(3);
  //##############################################################################

  /* 07. enum */
  //##############################################################################
    enum Color { RED, GREEN, BLUE };
    enum Color my_color = GREEN;
    if (my_color == GREEN) printf("Color is green\n");
  //##############################################################################

  /* 08. union */
  //##############################################################################
    union Data {
        int i;
        float f;
    };
    union Data data;
    data.i = 42;
    printf("Union int: %d\n", data.i);
    data.f = 3.14f;
    printf("Union float: %.2f\n", data.f);
  //##############################################################################

  /* 09. macro */
  //##############################################################################
    printf("PI is %.2f\n", PI);
  //##############################################################################

  /* 10. dynamic memory */
  //##############################################################################
    int *dyn = (int *)malloc(3 * sizeof(int));
    if (dyn != NULL) {
        for (int i = 0; i < 3; i++) dyn[i] = i * 10;
        for (int i = 0; i < 3; i++) printf("dyn[%d] = %d\n", i, dyn[i]);
        free(dyn);
    }
  //##############################################################################

  /* 11. bitwise operations */
  //##############################################################################
    unsigned char x = 0x0F;
    unsigned char y = 0xF0;
    printf("x & y = 0x%X\n", x & y);
  //##############################################################################

  /* end of main */
  return 0;
}

int add(int a, int b) {
    return a + b;
}

void recursive_function(int n) {
    if (n <= 0) {
        printf("Recursion end\n");
        return;
    }
    printf("Recursion level %d\n", n);
    recursive_function(n - 1);
}

